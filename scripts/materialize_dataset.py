"""Materialize the historical research panel from downloaded source files.

The command only reads local files under data/raw by default. It does not
change the final lockbox and it records SHA-256 provenance for every input.

Example:
  FRED/ALFRED files must first be downloaded with ingest_real_data.py.
  python scripts/materialize_dataset.py --market data/raw/market_index_spx.csv \
      --fred UNRATE=data/raw/fred_UNRATE.csv CPIAUCSL=data/raw/fred_CPIAUCSL.csv \
      --events data/raw/events_gdelt.csv \
      --output data/processed/research_dataset.parquet
"""

from __future__ import annotations

import argparse
from pathlib import Path

from market_predictor.data_sources import align_fred_point_in_time
from market_predictor.dataset import build_manifest, load_events, load_market, materialize_macro, write_manifest


def parse_fred(items: list[str]) -> dict[str, str]:
    result: dict[str, str] = {}
    for item in items:
        if "=" not in item:
            raise SystemExit(f"Invalid --fred value: {item!r}; expected SERIES=PATH")
        series, path = item.split("=", 1)
        if not series or not path:
            raise SystemExit(f"Invalid --fred value: {item!r}")
        result[series] = path
    return result


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--market", required=True)
    parser.add_argument("--fred", nargs="*", default=[])
    parser.add_argument("--events", nargs="*", default=[])
    parser.add_argument("--output", default="data/processed/research_dataset.parquet")
    parser.add_argument("--manifest", default="data/processed/research_dataset.manifest.json")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    market_path = Path(args.market)
    fred_files = parse_fred(args.fred)
    event_paths = [Path(item) for item in args.events]

    market = load_market(market_path)
    macro = materialize_macro(market.index, fred_files, align_fred_point_in_time) if fred_files else None

    panel = market.copy()
    if macro is not None:
        panel = panel.join(macro.drop(columns=[c for c in macro.columns if c.endswith("_vintage")]))

    # Event features are intentionally generated by the existing event feature
    # engine in the prediction pipeline. Here we retain a clean event table
    # separately rather than silently aggregating it in a way that could hide
    # publication-time mistakes.
    events = load_events(event_paths)

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    panel.to_parquet(output)
    events_path = output.with_name(output.stem + "_events.csv")
    events.to_csv(events_path, index=False)

    inputs = [market_path, *map(Path, fred_files.values()), *event_paths]
    manifest = build_manifest(
        inputs,
        dataset_name=output.stem,
        start=str(panel.index.min().date()) if not panel.empty else None,
        end=str(panel.index.max().date()) if not panel.empty else None,
    )
    manifest["outputs"] = {"panel": str(output), "events": str(events_path)}
    write_manifest(manifest, args.manifest)
    print(f"Wrote {output}")
    print(f"Wrote {events_path}")
    print(f"Wrote {args.manifest}")


if __name__ == "__main__":
    main()
